-- Schema of the restaurant application (matches the JPA entities in ro.tss.restaurant.model).

CREATE TABLE restaurant_tables (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number INTEGER NOT NULL,
    seats  INTEGER NOT NULL,
    CONSTRAINT uk_restaurant_tables_number UNIQUE (number),
    CONSTRAINT ck_restaurant_tables_seats CHECK (seats BETWEEN 1 AND 20)
);

CREATE TABLE menu_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255)   NOT NULL,
    description VARCHAR(255),
    category    VARCHAR(255)   NOT NULL,
    price       NUMERIC(10, 2) NOT NULL,
    available   BOOLEAN        NOT NULL,
    CONSTRAINT uk_menu_items_name UNIQUE (name),
    CONSTRAINT ck_menu_items_category CHECK (category IN ('APPETIZER', 'MAIN_COURSE', 'DESSERT', 'DRINK')),
    CONSTRAINT ck_menu_items_price CHECK (price > 0)
);

CREATE TABLE reservations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(255) NOT NULL,
    phone         VARCHAR(255) NOT NULL,
    table_id      BIGINT       NOT NULL REFERENCES restaurant_tables (id),
    date_time     TIMESTAMP(6) NOT NULL,
    party_size    INTEGER      NOT NULL
);
CREATE INDEX ix_reservations_table_date_time ON reservations (table_id, date_time);

CREATE TABLE orders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id   BIGINT       NOT NULL REFERENCES restaurant_tables (id),
    status     VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_orders_status CHECK (status IN ('NEW', 'IN_PREPARATION', 'SERVED', 'PAID', 'CANCELLED'))
);
CREATE INDEX ix_orders_table ON orders (table_id);
CREATE INDEX ix_orders_status ON orders (status);

-- order_id is nullable: Hibernate inserts the line first and then links it to the order
-- (unidirectional @OneToMany with @JoinColumn).
CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT REFERENCES orders (id) ON DELETE CASCADE,
    menu_item_id BIGINT         NOT NULL REFERENCES menu_items (id),
    quantity     INTEGER        NOT NULL,
    unit_price   NUMERIC(10, 2) NOT NULL,
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_order_items_order ON order_items (order_id);
CREATE INDEX ix_order_items_menu_item ON order_items (menu_item_id);
